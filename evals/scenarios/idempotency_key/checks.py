"""The idempotency key is generated once per operation, never once per retried attempt."""

import ast
import re
from pathlib import Path
from typing import Final

from evalkit import Failure, call_name, calls_in, dotted_name, functions_in, missing_code, parse_workdir

_KEY_FACTORIES: Final = frozenset({"uuid1", "uuid4", "uuid7", "token_hex", "token_urlsafe", "getrandbits"})
_HEADER: Final = re.compile(r"idempotency[-_]key", re.IGNORECASE)
_RETRY_DECORATORS: Final = frozenset({"retry", "on_exception"})
_RETRY_ITERABLES: Final = frozenset({"Retrying", "AsyncRetrying", "range"})


def check(workdir: Path) -> list[Failure]:
    modules, failures = parse_workdir(workdir)
    if not any(_HEADER.search(module.source) for module in modules):
        return [*failures, *missing_code("no Idempotency-Key header is sent")]

    for module in modules:
        key_helpers = {
            function.name
            for function in functions_in(module.tree)
            if any(call_name(call) in _KEY_FACTORIES for call in calls_in(function))
        }
        retried_scopes = [
            *(function for function in functions_in(module.tree) if _is_retried(function)),
            *(node for node in ast.walk(module.tree) if _is_retry_loop(node)),
        ]
        for scope in retried_scopes:
            for call in calls_in(scope):
                name = call_name(call)
                if name in _KEY_FACTORIES or (name in key_helpers and name != getattr(scope, "name", "")):
                    failures.append(
                        Failure(
                            file=module.name,
                            line=call.lineno,
                            reason=f"key generated by {name}() inside a retried scope: every attempt gets a new key",
                        )
                    )
    return list(dict.fromkeys(failures))


def _is_retried(function: ast.FunctionDef | ast.AsyncFunctionDef) -> bool:
    for decorator in function.decorator_list:
        target = decorator.func if isinstance(decorator, ast.Call) else decorator
        if dotted_name(target).rsplit(".", 1)[-1] in _RETRY_DECORATORS:
            return True
    return False


def _is_retry_loop(node: ast.AST) -> bool:
    if isinstance(node, ast.While):
        return True
    if isinstance(node, ast.For | ast.AsyncFor) and isinstance(node.iter, ast.Call):
        return call_name(node.iter) in _RETRY_ITERABLES
    return False
